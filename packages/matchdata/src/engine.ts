// Stats engine: stage (b) of the pipeline. Interprets raw synthetic events into football states,
// statistics and detected moments. Everything here is deterministic code; agents only explain it.
import type { MatchDataset, Player, Side, SynthEvent } from "./types.js";

const MIN = 60_000;
const L = 105;
const WINDOW = 5; // minutes in the rolling window for control and chaos
const clamp = (n: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, n));
const r1 = (n: number) => Math.round(n * 10) / 10;

/** x in the given side's attacking frame (0 = own goal line, 105 = opponent's). */
const attackX = (side: Side, x: number) => (side === "home" ? x : L - x);

export type PassQuality = {
  attempts: number;
  completed: number;
  accuracy: number;
  avgDistance: number;
  avgDifficulty: number;
  /** Completed passes with difficulty >= 0.5. */
  hardCompleted: number;
  /** Completed passes that moved the ball 10 m or more towards goal. */
  progressive: number;
  avgSpeedKmh: number;
};

export type ControlPoint = {
  minute: number;
  period: 1 | 2;
  /** 0..100. 50 is balanced, above 50 home control, below 50 away control. */
  homeControl: number;
  /** 0..100. How broken-up and end-to-end play is. */
  chaos: number;
  state: "home_control" | "away_control" | "balanced" | "chaos";
  /** -100..100. Positive: home side carrying the threat. */
  momentum: number;
};

export type Evidence = { eventIds: string[]; metrics: Record<string, number | string> };

export type Moment = {
  id: string;
  t: number;
  minute: number;
  period: 1 | 2;
  kind: "goal" | "big_chance" | "card" | "sub" | "momentum_swing" | "state_change" | "speed" | "distance" | "hard_pass";
  side?: Side;
  playerId?: string;
  playerName?: string;
  /** Template sentence generated by code. Agents may rephrase it but never change its numbers. */
  headline: string;
  /** 1..3, for ranking on screen. */
  weight: number;
  evidence: Evidence;
};

export type PlayerLine = {
  playerId: string;
  name: string;
  number: number;
  side: Side;
  distanceKm: number;
  topSpeedKmh: number;
  passes: PassQuality;
  shots: number;
  xg: number;
};

export type MatchInsights = {
  asOfSeq: number;
  minute: number;
  passQuality: Record<Side, PassQuality>;
  speed: {
    fastestShot: { speedKmh: number; playerId: string; playerName: string; minute: number; eventId: string } | null;
    fastestPass: { speedKmh: number; playerId: string; playerName: string; minute: number; eventId: string } | null;
    avgShotSpeedKmh: Record<Side, number>;
  };
  timeline: ControlPoint[];
  now: ControlPoint | null;
  players: PlayerLine[];
  moments: Moment[];
};

function emptyPQ() {
  return { attempts: 0, completed: 0, dist: 0, diff: 0, hard: 0, prog: 0, speed: 0 };
}
type PQAcc = ReturnType<typeof emptyPQ>;
function finishPQ(a: PQAcc): PassQuality {
  return {
    attempts: a.attempts,
    completed: a.completed,
    accuracy: a.attempts ? Math.round((a.completed / a.attempts) * 100) : 0,
    avgDistance: a.attempts ? r1(a.dist / a.attempts) : 0,
    avgDifficulty: a.attempts ? Math.round((a.diff / a.attempts) * 100) / 100 : 0,
    hardCompleted: a.hard,
    progressive: a.prog,
    avgSpeedKmh: a.attempts ? r1(a.speed / a.attempts) : 0,
  };
}

const DISTANCE_MILESTONE_M = 10_000;
/** Only the first few players past the milestone make a moment; the rest show in the player table. */
const DISTANCE_MOMENTS = 3;
const SPRINT_KMH = 34;
const ROCKET_KMH = 110;
const STATE_COOLDOWN = 5;
const SWING_COOLDOWN = 6;

export function analyse(d: MatchDataset, seen: SynthEvent[]): MatchInsights {
  const players = new Map<string, Player & { side: Side }>();
  for (const p of d.home.players) players.set(p.id, { ...p, side: "home" });
  for (const p of d.away.players) players.set(p.id, { ...p, side: "away" });
  const name = (id?: string) => (id ? players.get(id)?.name ?? id : "");

  const teamPQ = { home: emptyPQ(), away: emptyPQ() };
  const playerPQ = new Map<string, PQAcc>();
  const playerShots = new Map<string, { shots: number; xg: number }>();
  const physical = new Map<string, { distanceM: number; topSpeedKmh: number }>();
  const moments: Moment[] = [];
  const shotSpeeds = { home: [] as number[], away: [] as number[] };
  let fastestShot: MatchInsights["speed"]["fastestShot"] = null;
  let fastestPass: MatchInsights["speed"]["fastestPass"] = null;

  const add = (e: SynthEvent, m: Omit<Moment, "id" | "t" | "minute" | "period">) =>
    moments.push({ id: `${e.id}:${m.kind}`, t: e.t, minute: e.minute, period: e.period, ...m });

  // Per-minute buckets for control, chaos and momentum.
  type Bucket = {
    minute: number;
    period: 1 | 2;
    pass: Record<Side, number>;
    comp: Record<Side, number>;
    terr: Record<Side, number>;
    threat: Record<Side, number>;
    switches: number;
    fouls: number;
    shots: number;
  };
  const buckets: Bucket[] = [];
  const bucket = (e: SynthEvent) => {
    const i = Math.floor(e.t / MIN);
    for (let k = buckets.length; k <= i; k++) {
      buckets.push({ minute: e.minute, period: e.period, pass: { home: 0, away: 0 }, comp: { home: 0, away: 0 }, terr: { home: 0, away: 0 }, threat: { home: 0, away: 0 }, switches: 0, fouls: 0, shots: 0 });
    }
    const b = buckets[i]!;
    b.minute = e.minute;
    b.period = e.period;
    return b;
  };

  const awarded = new Set<string>();
  let distanceMoments = 0;
  for (let i = 0; i < seen.length; i++) {
    const e = seen[i]!;
    const b = bucket(e);
    const s = e.side;

    if (e.type === "pass" && s && e.playerId) {
      const ok = e.outcome === "complete";
      const forward = e.x !== undefined && e.endX !== undefined ? attackX(s, e.endX) - attackX(s, e.x) : 0;
      for (const acc of [teamPQ[s], playerPQ.get(e.playerId) ?? (playerPQ.set(e.playerId, emptyPQ()), playerPQ.get(e.playerId)!)]) {
        acc.attempts++;
        acc.dist += e.distance ?? 0;
        acc.diff += e.difficulty ?? 0;
        acc.speed += e.speedKmh ?? 0;
        if (ok) {
          acc.completed++;
          if ((e.difficulty ?? 0) >= 0.5) acc.hard++;
          if (forward >= 10) acc.prog++;
        }
      }
      b.pass[s]++;
      if (ok) b.comp[s]++;
      b.terr[s] += attackX(s, e.x ?? 52.5);
      if (ok && e.endX !== undefined && attackX(s, e.endX) > 70) b.threat[s] += 0.12;
      if (ok && (e.speedKmh ?? 0) > (fastestPass?.speedKmh ?? 0)) {
        fastestPass = { speedKmh: e.speedKmh!, playerId: e.playerId, playerName: name(e.playerId), minute: e.minute, eventId: e.id };
      }
      if (ok && (e.difficulty ?? 0) >= 0.75 && !awarded.has(`hard:${e.playerId}`)) {
        awarded.add(`hard:${e.playerId}`);
        add(e, {
          kind: "hard_pass", side: s, playerId: e.playerId, playerName: name(e.playerId), weight: 1,
          headline: `${name(e.playerId)} completes a ${Math.round(e.distance ?? 0)} m pass rated ${Math.round((e.difficulty ?? 0) * 100)}/100 for difficulty${e.underPressure ? " under pressure" : ""}.`,
          evidence: { eventIds: [e.id], metrics: { distanceM: e.distance ?? 0, difficulty: e.difficulty ?? 0, speedKmh: e.speedKmh ?? 0 } },
        });
      }
    } else if (e.type === "shot" && s && e.playerId) {
      b.shots++;
      b.threat[s] += (e.xg ?? 0) * 3;
      const ps = playerShots.get(e.playerId) ?? { shots: 0, xg: 0 };
      playerShots.set(e.playerId, { shots: ps.shots + 1, xg: ps.xg + (e.xg ?? 0) });
      shotSpeeds[s].push(e.speedKmh ?? 0);
      if ((e.speedKmh ?? 0) > (fastestShot?.speedKmh ?? 0)) {
        fastestShot = { speedKmh: e.speedKmh!, playerId: e.playerId, playerName: name(e.playerId), minute: e.minute, eventId: e.id };
      }
      if (e.outcome === "goal") {
        const assist = [...seen.slice(Math.max(0, i - 4), i)].reverse().find((p) => p.type === "pass" && p.recipientId === e.playerId && p.side === s);
        add(e, {
          kind: "goal", side: s, playerId: e.playerId, playerName: name(e.playerId), weight: 3,
          headline: `GOAL. ${name(e.playerId)} scores from ${Math.round(e.distance ?? 0)} m (xG ${(e.xg ?? 0).toFixed(2)}), shot at ${Math.round(e.speedKmh ?? 0)} km/h${assist ? `, set up by ${name(assist.playerId)}` : ""}.`,
          evidence: { eventIds: [e.id, ...(assist ? [assist.id] : [])], metrics: { xg: e.xg ?? 0, distanceM: e.distance ?? 0, speedKmh: e.speedKmh ?? 0 } },
        });
      } else if ((e.xg ?? 0) >= 0.25) {
        add(e, {
          kind: "big_chance", side: s, playerId: e.playerId, playerName: name(e.playerId), weight: 2,
          headline: `Big chance: ${name(e.playerId)}'s shot (xG ${(e.xg ?? 0).toFixed(2)}) is ${e.outcome === "saved" ? "saved" : e.outcome === "blocked" ? "blocked" : "off target"}.`,
          evidence: { eventIds: [e.id], metrics: { xg: e.xg ?? 0, distanceM: e.distance ?? 0 } },
        });
      }
      if ((e.speedKmh ?? 0) >= ROCKET_KMH && !awarded.has(`rocket:${e.playerId}`)) {
        awarded.add(`rocket:${e.playerId}`);
        add(e, {
          kind: "speed", side: s, playerId: e.playerId, playerName: name(e.playerId), weight: 1,
          headline: `${name(e.playerId)} hits a shot at ${Math.round(e.speedKmh ?? 0)} km/h.`,
          evidence: { eventIds: [e.id], metrics: { speedKmh: e.speedKmh ?? 0 } },
        });
      }
    } else if (e.type === "corner" && s) {
      b.threat[s] += 0.2;
    } else if (e.type === "possession_change") {
      b.switches++;
    } else if (e.type === "foul") {
      b.fouls++;
    } else if (e.type === "card" && s) {
      add(e, {
        kind: "card", side: s, playerId: e.playerId, playerName: name(e.playerId), weight: e.detail === "Red Card" ? 3 : 1,
        headline: `${e.detail ?? "Card"} for ${name(e.playerId)}.`,
        evidence: { eventIds: [e.id], metrics: {} },
      });
    } else if (e.type === "sub" && s) {
      add(e, {
        kind: "sub", side: s, playerId: e.recipientId, playerName: name(e.recipientId), weight: 1,
        headline: `${name(e.recipientId)} replaces ${name(e.playerId)}.`,
        evidence: { eventIds: [e.id], metrics: {} },
      });
    } else if (e.type === "telemetry") {
      for (const p of e.players ?? []) {
        const before = physical.get(p.playerId);
        physical.set(p.playerId, { distanceM: p.distanceM, topSpeedKmh: p.topSpeedKmh });
        const pl = players.get(p.playerId);
        if (!pl) continue;
        if ((before?.distanceM ?? 0) < DISTANCE_MILESTONE_M && p.distanceM >= DISTANCE_MILESTONE_M && distanceMoments < DISTANCE_MOMENTS) {
          distanceMoments++;
          add(e, {
            kind: "distance", side: pl.side, playerId: p.playerId, playerName: pl.name, weight: 1,
            headline: `${pl.name} is ${distanceMoments === 1 ? "the first player" : `player number ${distanceMoments}`} past ${DISTANCE_MILESTONE_M / 1000} km covered (${e.minute}').`,
            evidence: { eventIds: [e.id], metrics: { distanceM: p.distanceM } },
          });
        }
        if ((before?.topSpeedKmh ?? 0) < SPRINT_KMH && p.topSpeedKmh >= SPRINT_KMH) {
          add(e, {
            kind: "speed", side: pl.side, playerId: p.playerId, playerName: pl.name, weight: 1,
            headline: `${pl.name} reaches a top speed of ${p.topSpeedKmh} km/h.`,
            evidence: { eventIds: [e.id], metrics: { topSpeedKmh: p.topSpeedKmh } },
          });
        }
      }
    }
  }

  // ---- Control, chaos and momentum timeline ----
  const timeline: ControlPoint[] = [];
  const raws: ControlPoint["state"][] = [];
  let ewma = 0;
  let lastStateMoment = -Infinity;
  let lastSwingMoment = -Infinity;
  for (let i = 0; i < buckets.length; i++) {
    const win = buckets.slice(Math.max(0, i - WINDOW + 1), i + 1);
    const sum = (f: (b: Bucket) => number) => win.reduce((n, b) => n + f(b), 0);
    const pH = sum((b) => b.pass.home);
    const pA = sum((b) => b.pass.away);
    const passes = pH + pA;
    const accH = pH ? sum((b) => b.comp.home) / pH : 0.5;
    const accA = pA ? sum((b) => b.comp.away) / pA : 0.5;
    const terrH = pH ? sum((b) => b.terr.home) / pH / L : 0.5;
    const terrA = pA ? sum((b) => b.terr.away) / pA / L : 0.5;
    const share = passes ? pH / passes : 0.5;
    const homeControl = Math.round(100 * clamp(0.5 * share + 0.25 * (0.5 + (accH - accA)) + 0.25 * (0.5 + (terrH - terrA) / 2), 0, 1));

    const mins = win.length;
    const switchRate = sum((b) => b.switches) / mins;
    const accAll = passes ? (sum((b) => b.comp.home) + sum((b) => b.comp.away)) / passes : 0.8;
    const eventRate = (sum((b) => b.shots) + sum((b) => b.fouls)) / mins;
    const chaos = Math.round(100 * clamp(0.5 * clamp((switchRate - 1.5) / 4, 0, 1) + 0.3 * clamp((0.9 - accAll) / 0.3, 0, 1) + 0.2 * clamp(eventRate / 1.2, 0, 1), 0, 1));

    const b = buckets[i]!;
    ewma = 0.65 * ewma + 0.35 * (b.threat.home - b.threat.away);
    const momentum = Math.round(100 * Math.tanh(ewma * 1.5));
    const raw: ControlPoint["state"] = chaos >= 50 ? "chaos" : homeControl >= 58 ? "home_control" : homeControl <= 42 ? "away_control" : "balanced";
    // Hysteresis: the shown state only changes once the new reading holds for two minutes in a row.
    const prevState = timeline[i - 1]?.state ?? "balanced";
    const state = raw !== prevState && raws[i - 1] === raw ? raw : i === 0 ? raw : prevState;
    raws.push(raw);
    timeline.push({ minute: b.minute, period: b.period, homeControl, chaos, state, momentum });

    // Moments from the timeline (after the opening minutes settle), with cooldowns so the feed isn't spammed.
    if (i >= WINDOW) {
      const prev = timeline[i - 1]!;
      const anchor = seen.find((e) => Math.floor(e.t / MIN) === i);
      if (anchor && prev.state !== state && i - lastStateMoment >= STATE_COOLDOWN) {
        lastStateMoment = i;
        const label = { home_control: `${d.home.name} take control`, away_control: `${d.away.name} take control`, chaos: "The game turns chaotic", balanced: "The game settles into balance" }[state];
        moments.push({
          id: `${anchor.id}:state`, t: anchor.t, minute: b.minute, period: b.period, kind: "state_change", weight: 2,
          ...(state === "home_control" ? { side: "home" as Side } : state === "away_control" ? { side: "away" as Side } : {}),
          headline: `${label}: control index ${homeControl}/100 for ${d.home.short}, chaos ${chaos}/100 over the last ${WINDOW} minutes.`,
          evidence: { eventIds: [anchor.id], metrics: { homeControl, chaos, possessionShare: Math.round(share * 100), switchesPerMin: r1(switchRate), passAccuracy: Math.round(accAll * 100) } },
        });
      }
      const back = timeline[i - 3];
      if (anchor && back && Math.sign(back.momentum) !== Math.sign(momentum) && Math.abs(momentum - back.momentum) >= 90 && i - lastSwingMoment >= SWING_COOLDOWN) {
        lastSwingMoment = i;
        const side: Side = momentum > 0 ? "home" : "away";
        moments.push({
          id: `${anchor.id}:swing`, t: anchor.t, minute: b.minute, period: b.period, kind: "momentum_swing", side, weight: 2,
          headline: `Momentum swings to ${d[side].name}: from ${back.momentum} to ${momentum} in three minutes.`,
          evidence: { eventIds: [anchor.id], metrics: { from: back.momentum, to: momentum } },
        });
      }
    }
  }

  const avg = (xs: number[]) => (xs.length ? r1(xs.reduce((a, b) => a + b, 0) / xs.length) : 0);
  const playerLines: PlayerLine[] = [...players.values()]
    .filter((p) => physical.has(p.id) || playerPQ.has(p.id))
    .map((p) => ({
      playerId: p.id,
      name: p.name,
      number: p.number,
      side: p.side,
      distanceKm: r1((physical.get(p.id)?.distanceM ?? 0) / 1000),
      topSpeedKmh: physical.get(p.id)?.topSpeedKmh ?? 0,
      passes: finishPQ(playerPQ.get(p.id) ?? emptyPQ()),
      shots: playerShots.get(p.id)?.shots ?? 0,
      xg: Math.round((playerShots.get(p.id)?.xg ?? 0) * 100) / 100,
    }));

  moments.sort((a, b) => b.t - a.t || b.weight - a.weight);
  return {
    asOfSeq: seen.at(-1)?.seq ?? -1,
    minute: seen.at(-1)?.minute ?? 0,
    passQuality: { home: finishPQ(teamPQ.home), away: finishPQ(teamPQ.away) },
    speed: { fastestShot, fastestPass, avgShotSpeedKmh: { home: avg(shotSpeeds.home), away: avg(shotSpeeds.away) } },
    timeline,
    now: timeline.at(-1) ?? null,
    players: playerLines,
    moments,
  };
}
